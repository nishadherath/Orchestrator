#!/usr/bin/env python3
"""Write test/results/INDEX.md: one row per result file, so a reader can find what a decision cites.

Responsible for: docs/PLAN-6.md Stage D.3 (audit C5). test/results/ is a
pile of dated files, well-named enough for replay_routing.py and
backtest_ledger.py to find their own inputs by glob, but nothing maps a
file to the decision entry or plan stage that consumed it, and the only
way to find "the run D45 cites" was to read D45. This script derives
date, kind and bundle from each filename, records its size, and greps
docs/DECISIONS.md for which D-numbered entries cite it by name.

Deliberately does not: read a result file's own content (kind and
bundle come from the filename alone, the same convention
replay_routing.py and backtest_ledger.py already depend on being
accurate), or flag an uncited file as a problem: most files predate the
practice of citing a result by its filename, so absence here is not
evidence of anything.

Usage:
    python3 test/harness/results_index.py            write test/results/INDEX.md
    python3 test/harness/results_index.py --check     exit 1 if INDEX.md would change; write nothing
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
RESULTS_DIR = REPO_ROOT / "test" / "results"
DECISIONS = REPO_ROOT / "docs" / "DECISIONS.md"
INDEX = RESULTS_DIR / "INDEX.md"

DATE_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-(.+)$")
BUNDLE_RE = re.compile(r"\b[0-9a-f]{7}\b")
DECISION_HEADING_RE = re.compile(r"(?m)^## \S+ (D\d+)\.")

# Ordered longest-prefix-first so "system-controller" is not swallowed by a
# shorter, unrelated prefix; checked against the filename after its date.
KNOWN_KINDS = (
    "system-controller", "role-probe", "cost-rollup", "table-collapse",
    "toy-problem", "attractor-diagnosis", "e30-transcripts",
    "refusal-detector-calibration", "preregistration", "routing",
    "benchmark", "controller", "fleet", "dogfood", "harness", "backtest",
    "replay", "compaction", "decomposition", "classifier", "empirical",
)


def parse_name(name: str) -> tuple[str, str, str]:
    """Return (date, kind, bundle) derived from a result file's name alone."""
    m = DATE_RE.match(name)
    date, rest = (m.group(1), m.group(2)) if m else ("unknown", name)
    kind = next((k for k in KNOWN_KINDS if rest.startswith(k)), rest.split("-")[0].split(".")[0])
    bundle_m = BUNDLE_RE.search(rest)
    return date, kind, bundle_m.group() if bundle_m else ""


def citing_entries(name: str, decisions_text: str) -> list[str]:
    """D-numbers of every docs/DECISIONS.md entry whose text names this file."""
    headings = [(m.start(), m.group(1)) for m in DECISION_HEADING_RE.finditer(decisions_text)]
    if not headings:
        return []
    hits: set[str] = set()
    for m in re.finditer(re.escape(name), decisions_text):
        entry = next((d for start, d in reversed(headings) if start <= m.start()), None)
        if entry:
            hits.add(entry)
    return sorted(hits, key=lambda d: int(d[1:]))


def build_index() -> str:
    decisions_text = DECISIONS.read_text(encoding="utf-8") if DECISIONS.exists() else ""
    rows = []
    for path in sorted(RESULTS_DIR.iterdir()):
        if not path.is_file() or path.name == "INDEX.md":
            continue
        date, kind, bundle = parse_name(path.name)
        rows.append((date, kind, bundle, path.stat().st_size, path.name, citing_entries(path.name, decisions_text)))
    lines = [
        "# test/results/ index",
        "",
        "Generated by `test/harness/results_index.py` (docs/PLAN-6.md D.3, "
        "audit C5); regenerated by `check.py --record`, never hand-edited. "
        "Date, kind and bundle are derived from each filename alone, the "
        "same convention `replay_routing.py` and `backtest_ledger.py` "
        "already rely on being accurate. \"Cites\" lists every "
        "`docs/DECISIONS.md` entry whose text names the file; an empty "
        "cell means no entry names it by filename, not that no entry "
        "used its data.",
        "",
        f"{len(rows)} files.",
        "",
        "| Date | Kind | Bundle | Size | File | Cites |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
    ]
    for date, kind, bundle, size, name, cites in rows:
        lines.append(f"| {date} | {kind} | {bundle or '-'} | {size:,} | `{name}` | "
                      f"{', '.join(cites) if cites else '-'} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if INDEX.md would change; write nothing")
    args = ap.parse_args(argv)

    content = build_index()
    if args.check:
        current = INDEX.read_text(encoding="utf-8") if INDEX.exists() else None
        if current == content:
            print("unchanged")
            return 0
        print("test/results/INDEX.md would change; run without --check to update")
        return 1
    INDEX.write_text(content, encoding="utf-8", newline="\n")
    print(f"wrote {INDEX.relative_to(REPO_ROOT)}, {content.count(chr(10))} lines")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
